'use client';

import React, { useState } from 'react';
import {
  Sparkles,
  AlertCircle,
  TrendingUp,
  CheckCircle2,
  Zap,
  ArrowRight,
  ShieldAlert,
  Loader2
} from 'lucide-react';
import { AIRecommendationItem } from '../../types';

interface AIRecommendationsProps {
  recommendations: AIRecommendationItem[];
  onFixRecommendation: (rec: AIRecommendationItem) => void;
}

export const AIRecommendations: React.FC<AIRecommendationsProps> = ({
  recommendations,
  onFixRecommendation,
}) => {
  const [filter, setFilter] = useState<'All' | 'High' | 'Medium'>('All');
  const [fixingId, setFixingId] = useState<string | null>(null);
  const [fixedMap, setFixedMap] = useState<Record<string, boolean>>({});

  const filteredRecs = recommendations.filter((rec) => {
    if (filter === 'High') return rec.severity === 'High';
    if (filter === 'Medium') return rec.severity === 'Medium';
    return true;
  });

  const handleFix = (rec: AIRecommendationItem) => {
    setFixingId(rec.id);
    setTimeout(() => {
      setFixingId(null);
      setFixedMap((prev) => ({ ...prev, [rec.id]: true }));
      onFixRecommendation(rec);
    }, 1200);
  };

  return (
    <div className="bg-white rounded-xl border border-[#E5E7EB] shadow-2xs overflow-hidden font-sans">
      {/* Header */}
      <div className="p-5 border-b border-[#E5E7EB] flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div className="flex items-center gap-2">
          <div className="w-7 h-7 rounded-lg bg-blue-50 text-[#2563EB] flex items-center justify-center">
            <Sparkles className="w-4 h-4" />
          </div>
          <div>
            <h3 className="text-base font-bold text-[#111827] tracking-tight">AI Recommendations</h3>
            <p className="text-xs text-[#6B7280]">
              Prioritized high-impact visibility fixes generated by Reach Agent.
            </p>
          </div>
        </div>

        {/* Severity Tabs */}
        <div className="flex items-center bg-[#F8FAFC] p-1 rounded-lg border border-[#E5E7EB] text-xs font-medium self-start sm:self-center">
          {['All', 'High', 'Medium'].map((tab) => (
            <button
              key={tab}
              onClick={() => setFilter(tab as any)}
              className={`px-2.5 py-1 rounded-md transition-all ${
                filter === tab
                  ? 'bg-white text-[#111827] font-bold shadow-2xs border border-gray-200'
                  : 'text-[#6B7280] hover:text-[#111827]'
              }`}
            >
              {tab}
            </button>
          ))}
        </div>
      </div>

      {/* Card List */}
      <div className="p-4 sm:p-5 flex flex-col gap-4">
        {filteredRecs.map((rec) => {
          const isFixed = fixedMap[rec.id];
          const isFixing = fixingId === rec.id;

          const isHigh = rec.severity === 'High';
          const isMed = rec.severity === 'Medium';

          return (
            <div
              key={rec.id}
              className={`p-4 rounded-xl border transition-all ${
                isFixed
                  ? 'bg-emerald-50/40 border-emerald-200'
                  : 'bg-white border-[#E5E7EB] hover:border-gray-300 shadow-2xs hover:shadow-xs'
              }`}
            >
              {/* Top Row: Severity Badge & Category */}
              <div className="flex items-center justify-between mb-2">
                <span
                  className={`inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider ${
                    isHigh
                      ? 'bg-red-50 text-[#DC2626] border border-red-200'
                      : isMed
                      ? 'bg-amber-50 text-[#F59E0B] border border-amber-200'
                      : 'bg-blue-50 text-[#2563EB] border border-blue-200'
                  }`}
                >
                  <ShieldAlert className="w-3 h-3" />
                  {rec.severity} Severity
                </span>

                <span className="text-[11px] font-medium text-[#2563EB] bg-blue-50 px-2 py-0.5 rounded border border-blue-100">
                  {rec.estimatedImpact}
                </span>
              </div>

              {/* Problem Title */}
              <h4 className="text-sm font-bold text-[#111827] tracking-tight mb-1">
                {rec.title}
              </h4>

              {/* Problem Details */}
              <p className="text-xs text-[#6B7280] mb-2 font-normal leading-relaxed">
                <strong className="text-[#111827]">Problem:</strong> {rec.problem}
              </p>

              {/* Why It Matters */}
              <div className="p-2.5 rounded-lg bg-[#F8FAFC] border border-gray-100 text-xs text-[#111827] mb-3">
                <span className="font-semibold text-[#111827]">Why it matters: </span>
                <span className="text-[#6B7280]">{rec.whyItMatters}</span>
              </div>

              {/* Recommended Solution & Action */}
              <div className="flex items-center justify-between gap-3 pt-2 border-t border-gray-100">
                <div className="text-[11px] text-[#6B7280] font-medium line-clamp-1 max-w-[240px]">
                  Solution: {rec.recommendedSolution}
                </div>

                {isFixed ? (
                  <span className="inline-flex items-center gap-1 px-3 py-1.5 rounded-lg bg-emerald-100 text-[#16A34A] text-xs font-bold shrink-0">
                    <CheckCircle2 className="w-3.5 h-3.5" />
                    Fixed Automatically
                  </span>
                ) : (
                  <button
                    onClick={() => handleFix(rec)}
                    disabled={isFixing}
                    className="inline-flex items-center gap-1.5 px-3.5 py-1.5 rounded-lg bg-[#2563EB] text-white hover:bg-blue-700 text-xs font-semibold transition-all shadow-xs shrink-0 active:scale-98 disabled:opacity-75"
                  >
                    {isFixing ? (
                      <>
                        <Loader2 className="w-3.5 h-3.5 animate-spin" />
                        <span>Applying Fix...</span>
                      </>
                    ) : (
                      <>
                        <Zap className="w-3.5 h-3.5" />
                        <span>Fix Automatically</span>
                      </>
                    )}
                  </button>
                )}
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};

